/** Privacy policy, terms of use, and accessibility statement — honest to the
 * architecture (local-first, no tracking, AI disclosure). Drafts for a lawyer
 * review before any paid launch. */
import { useEffect, useState } from "react";

const UPDATED = "July 14, 2026";

function Privacy() {
  return (
    <div className="legal-body">
      <h3>Privacy Policy</h3>
      <p><i>Last updated {UPDATED}</i></p>
      <p><b>The short version:</b> your degree plan lives in your browser, not on our servers.</p>
      <ul>
        <li><b>Plan data</b> (majors, courses, progress) is stored locally on your device. If you choose to
          sign in, your plan syncs to your private account space (Supabase, US region) so other devices can
          load it; only your account can read it. You can delete it at any time with "Start over" and by
          signing out.</li>
        <li><b>AI advisor messages</b> are sent through our server to OpenAI to generate responses. We do not
          store your conversations; OpenAI processes them under its API terms (not used to train models).
          Don't paste sensitive personal information into the chat.</li>
        <li><b>Sign-in</b> (optional) uses Google or Microsoft; we receive your email address for account
          identification and nothing else.</li>
        <li><b>No tracking:</b> no advertising, no analytics cookies, no sale of data. Rate-limit counters
          use your IP transiently and expire within ~26 hours.</li>
        <li><b>Requests:</b> open an issue at <a href="https://github.com/okayojas/lionsdegree/issues"
          target="_blank" rel="noopener noreferrer">github.com/okayojas/lionsdegree</a> to access or delete
          any synced data. Sync is off unless you turned it on, in which case your data lives in the
          Supabase project of whoever runs the instance you signed in to.</li>
      </ul>
      <p>This service is intended for users 13 and older.</p>
    </div>
  );
}

